#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."

version="${1:?Pass the release version, such as 0.1.0.}"
VERSION="$version" UNIVERSAL=1 bash build.sh

app="$PWD/.build/LP Clock.app"
binary="$app/Contents/MacOS/LPClock"
lipo "$binary" -verify_arch arm64 x86_64
codesign --verify --strict "$app"

mkdir -p dist
archive="lp-clock_macOS_universal.zip"
rm -f "dist/$archive"
ditto -c -k --sequesterRsrc --keepParent "$app" "dist/$archive"
(cd dist && shasum -a 256 "$archive" >checksums.txt)
sha256="$(shasum -a 256 "dist/$archive" | awk '{print $1}')"

# Publish a cask for the exact archive uploaded to the GitHub release.
cat >dist/lp-clock.rb <<EOF
# Generated by LP Clock's release workflow.
cask "lp-clock" do
  version "$version"
  sha256 "$sha256"

  url "https://github.com/eiri/lp-clock/releases/download/v#{version}/$archive"
  name "LP Clock"
  desc "Binary clock for the Launchpad Mini MK3"
  homepage "https://github.com/eiri/lp-clock"

  depends_on macos: ">= :ventura"

  app "LP Clock.app"

  # The prototype uses ad-hoc signing, without Apple notarization.
  postflight do
    system_command "/usr/bin/xattr",
                   args: ["-dr", "com.apple.quarantine", "#{appdir}/LP Clock.app"],
                   must_succeed: false
  end

  uninstall quit: "ca.eiri.lp-clock"
end
EOF
ruby -c dist/lp-clock.rb
